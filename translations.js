function getLang() {
  return localStorage.getItem('ema_lang') || 'fr';
}

function t(key) {
  var lang = getLang();
  return (translations[lang] && translations[lang][key]) ? translations[lang][key] : (translations['fr'][key] || key);
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(function(el) {
    el.textContent = t(el.getAttribute('data-i18n'));
  });
}

function setLang(lang) {
  localStorage.setItem('ema_lang', lang);
  applyTranslations();
}

function translateLeague(name) {
  var lang = getLang();
  var dict = translations[lang] && translations[lang].leagues ? translations[lang].leagues : {};
  return dict[name] || name;
}


